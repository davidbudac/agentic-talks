#!/usr/bin/env python3
"""Generate the SYNTHETIC sample data set in this folder. Nothing here is measured.

    python3 sample-results/generate_synthetic.py

Writes, all marked synthetic:
  export.jsonl                 board lines for 10 made-up pairs (pair ids SYNTH-01..SYNTH-10)
  traces/*.jsonl               two stream-json transcripts (first event: synthetic_notice)
  lab5-judge/sonnet/s*.json    judge scores in judge.sh's output format
  lab5-human-scores.csv        one made-up pair's hand scores

The shapes follow Claude Code 2.1.x output and the lab's own schema; the numbers
come from a seeded random generator with plausible ranges (a Sonnet session on
this repo: ~8-16 turns, 0.2-0.5M tokens, ~90% cache reads). They exist so labs
2-5 and the board can be rehearsed offline. They are not results, and they are
not predictions of what real runs will show. record-facilitator-run.sh replaces
them with a real run.
"""
import csv
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
LAB = HERE.parent
APP = LAB / "invoice-app"
SEED = 20260924
NOTE = ("SYNTHETIC sample data generated by sample-results/generate_synthetic.py (seed "
        f"{SEED}). Not a measurement. Replace with ./record-facilitator-run.sh.")
PRICES = {"haiku": (1.0, 5.0), "sonnet": (2.0, 10.0), "opus": (4.0, 20.0)}
MODELS = {"haiku": "claude-haiku-4-5", "sonnet": "claude-sonnet-5", "opus": "claude-opus-5-5"}
rng = random.Random(SEED)


def compact(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def cost_of(alias, inp, out, read, write):
    p_in, p_out = PRICES[alias]
    return round((inp * p_in + out * p_out + read * p_in * 0.1 + write * p_in * 1.25) / 1e6, 6)


def run_line(pair, lab, variant, task, run, alias, passed, turns_mu, bloat=1.0, turn_scale=1.0):
    turns = max(4, round(rng.gauss(turns_mu, 2.5) * turn_scale))
    prefix = rng.randint(24000, 30000) + (3600 if variant == "bloated" else 280)
    calls = turns + rng.randint(0, 3)
    read = int(sum(prefix + i * rng.randint(1200, 2600) for i in range(1, calls)) * bloat ** 0.2)
    write = int(prefix + calls * rng.randint(700, 1400))
    out = int(calls * rng.randint(250, 650) * (1.3 if alias == "opus" else 1.0))
    inp = calls * rng.randint(3, 8)
    seconds = round(calls * rng.uniform(6, 14) + rng.uniform(10, 40), 1)
    if alias == "haiku":
        seconds = round(seconds * 0.6, 1)
    return {"v": 1, "pair": pair, "lab": lab, "variant": variant, "task": task, "run": run,
            "passed": passed, "turns": turns, "input_tokens": inp, "output_tokens": out,
            "cache_read_tokens": read, "cache_write_tokens": write,
            "cost_usd": cost_of(alias, inp, out, read, write), "duration_s": seconds, "model": MODELS[alias]}


def export_lines():
    lines = []
    lab1_tasks = ("fix-date-parser", "jpy-rounding")
    lab2_task = "report-sort-accents"
    p_sonnet = {"fix-date-parser": 0.9, "jpy-rounding": 0.75, "report-sort-accents": 0.7}
    p_haiku = {"fix-date-parser": 0.8, "jpy-rounding": 0.45, "report-sort-accents": 0.5}
    p_opus = {"fix-date-parser": 0.95, "jpy-rounding": 0.85, "report-sort-accents": 0.85}
    quality = {"s1": 1.3, "s2": 2.8, "s3": 3.6, "s4": 4.8, "s5": 2.0, "s6": 3.4, "s7": 2.4, "s8": 4.7}
    authors = {"s1": "human", "s2": "model", "s3": "model", "s4": "human",
               "s5": "model", "s6": "human", "s7": "human", "s8": "model"}
    for index in range(1, 11):
        pair = f"SYNTH-{index:02d}"
        lines.append({"v": 1, "pair": pair, "lab": "lab1", "kind": "prediction",
                      "variant": "lean" if rng.random() < 0.6 else "bloated"})
        for task in lab1_tasks:
            for variant in ("lean", "bloated"):
                passed = rng.random() < p_sonnet[task] - (0.05 if variant == "bloated" else 0)
                lines.append(run_line(pair, "lab1", variant, task, 1, "sonnet", passed, 11,
                                      bloat=1.3 if variant == "bloated" else 1.0,
                                      turn_scale=1.1 if variant == "bloated" else 1.0))
        for run in range(1, 4):
            for variant in ("lean", "bloated"):
                passed = rng.random() < p_sonnet[lab2_task] - (0.05 if variant == "bloated" else 0)
                lines.append(run_line(pair, "lab2", variant, lab2_task, run, "sonnet", passed, 12,
                                      bloat=1.3 if variant == "bloated" else 1.0,
                                      turn_scale=1.1 if variant == "bloated" else 1.0))
        for sample, q in quality.items():
            human = max(1, min(5, round(q + rng.gauss(0, 0.7))))
            bias = 0.4 if authors[sample] == "model" else 0.0
            judge = max(1, min(5, round(q + 0.3 + bias + rng.gauss(0, 0.5))))
            lines.append({"v": 1, "pair": pair, "lab": "lab5", "kind": "judge", "sample": sample,
                          "human": human, "judge": judge, "author": authors[sample]})
            line = run_line(pair, "lab5", "sonnet", sample, 1, "sonnet", None, 1)
            line.update(turns=1, input_tokens=rng.randint(2100, 2600), output_tokens=rng.randint(70, 140),
                        cache_read_tokens=0, cache_write_tokens=0, duration_s=round(rng.uniform(3, 7), 1))
            line["cost_usd"] = cost_of("sonnet", line["input_tokens"], line["output_tokens"], 0, 0)
            lines.append(line)
        models = ["haiku", "sonnet"] + (["opus"] if index <= 3 else [])
        for alias in models:
            probs = {"haiku": p_haiku, "sonnet": p_sonnet, "opus": p_opus}[alias]
            for task in (*lab1_tasks, lab2_task):
                for run in (1, 2):
                    passed = rng.random() < probs[task]
                    lines.append(run_line(pair, "lab6", alias, task, run, alias, passed,
                                          {"haiku": 14, "sonnet": 11, "opus": 9}[alias]))
    return lines


def trace(path, variant, waste):
    """One synthetic stream-json session on report-sort-accents with real file contents."""
    root = "/var/folders/xx/T/lab-run.SYNTH/repo"
    src = "src/main/java/com/example/invoicing"
    test = "src/test/java/com/example/invoicing"
    model = MODELS["sonnet"]
    events = [{"type": "system", "subtype": "synthetic_notice", "note": NOTE},
              {"type": "system", "subtype": "init", "session_id": "synthetic", "model": model,
               "cwd": root, "tools": ["Bash", "Edit", "Glob", "Grep", "Read", "Write"]}]
    calls = []
    context = 26800 + (3600 if variant == "bloated" else 280)
    counter = [0]

    def assistant(content):
        counter[0] += 1
        n = counter[0]
        usage = {"input_tokens": 4, "cache_read_input_tokens": context if n > 1 else 0,
                 "cache_creation_input_tokens": context if n == 1 else rng.randint(300, 1800),
                 "output_tokens": rng.randint(120, 700)}
        calls.append(usage)
        events.append({"type": "assistant", "session_id": "synthetic", "parent_tool_use_id": None,
                       "message": {"id": f"msg_synth_{variant}_{n}", "model": model, "role": "assistant",
                                   "content": content, "usage": usage}})

    def tool(name, data, result, error=False):
        nonlocal context
        tid = f"toolu_synth_{variant}_{counter[0] + 1}"
        assistant([{"type": "tool_use", "id": tid, "name": name, "input": data}])
        events.append({"type": "user", "session_id": "synthetic", "parent_tool_use_id": None,
                       "message": {"role": "user", "content": [{"type": "tool_result", "tool_use_id": tid,
                                                                "content": result, "is_error": error}]}})
        context += len(result) // 4 + 80

    def read(rel):
        tool("Read", {"file_path": f"{root}/{rel}"}, (APP / rel).read_text(encoding="utf-8"))

    plan = ("I'll look at Report.summarise and CustomerNames.comparator, add a failing test for accented "
            "names in ReportTest, switch the sort to the collator-based comparator with currency as the "
            "tie-breaker, then run ./mvnw -q test.")
    assistant([{"type": "text", "text": plan}])
    tool("Grep", {"pattern": "sort", "path": f"{root}/src"}, f"{src}/Report.java:56:        entries.sort(...)\n"
         f"{src}/CustomerNames.java:49:     * Human-friendly order")
    read(f"{src}/Report.java")
    read(f"{src}/CustomerNames.java")
    if waste:
        read(f"{src}/Invoice.java")
        read(f"{src}/Report.java")  # re-read, nothing changed
        assistant([{"type": "text", "text": "So the plan: look at Report.summarise and CustomerNames.comparator, "
                    "add a failing test for accented names in ReportTest, switch the sort to the collator-based "
                    "comparator with currency as the tie-breaker, and run ./mvnw -q test."}])
        tool("Bash", {"command": "mvn -q test", "description": "Run tests"},
             "Permission to use Bash with command mvn -q test has been denied.", error=True)
        tool("Bash", {"command": "mvn -q test", "description": "Run tests"},
             "Permission to use Bash with command mvn -q test has been denied.", error=True)
        tool("Grep", {"pattern": "sort", "path": f"{root}/src"}, f"{src}/Report.java:56:        entries.sort(...)")
    read(f"{test}/ReportTest.java")
    tool("Edit", {"file_path": f"{root}/{test}/ReportTest.java", "old_string": "    @Test\n    void currencyFilter",
                  "new_string": "    @Test\n    void ordersAccentedNamesLikeTheirPlainLetters() { ... }\n\n    @Test\n    void currencyFilter"},
         f"The file {root}/{test}/ReportTest.java has been updated.")
    tool("Bash", {"command": "./mvnw -q test", "description": "Run tests (expect the new one to fail)"},
         "[ERROR] Failures: \n[ERROR]   ReportTest.ordersAccentedNamesLikeTheirPlainLetters:48 expected: "
         "<[Čapek, élodie, Zeta]> but was: <[Zeta, élodie, Čapek]>\n[ERROR] Tests run: 58, Failures: 1", error=True)
    if waste:
        read(f"{src}/Report.java")  # re-read after only a test edit
    tool("Edit", {"file_path": f"{root}/{src}/Report.java",
                  "old_string": "entries.sort(Comparator.comparing(Entry::customerName).thenComparing(Entry::currency));",
                  "new_string": "entries.sort(Comparator.comparing(Entry::customerName, CustomerNames.comparator())\n"
                                "                .thenComparing(Entry::currency));"},
         f"The file {root}/{src}/Report.java has been updated.")
    tool("Bash", {"command": "./mvnw -q test", "description": "Run tests"}, "")
    assistant([{"type": "text", "text": "Report entries are now ordered with CustomerNames.comparator() "
                "(accent- and case-insensitive), then by currency. Added ReportTest."
                "ordersAccentedNamesLikeTheirPlainLetters; ./mvnw -q test passes (58 tests)."}])
    totals = {k: sum(c[k] for c in calls) for k in calls[0]}
    cost = cost_of("sonnet", totals["input_tokens"], totals["output_tokens"],
                   totals["cache_read_input_tokens"], totals["cache_creation_input_tokens"])
    events.append({"type": "result", "subtype": "success", "is_error": False, "session_id": "synthetic",
                   "num_turns": len(calls), "duration_ms": len(calls) * 9000, "duration_api_ms": len(calls) * 7000,
                   "total_cost_usd": cost, "result": events[-1]["message"]["content"][0]["text"],
                   "stop_reason": "end_turn", "terminal_reason": "completed", "usage": totals,
                   "modelUsage": {model: {"inputTokens": totals["input_tokens"], "outputTokens": totals["output_tokens"],
                                          "cacheReadInputTokens": totals["cache_read_input_tokens"],
                                          "cacheCreationInputTokens": totals["cache_creation_input_tokens"],
                                          "costUSD": cost}},
                   "permission_denials": [{"tool_name": "Bash", "tool_input": {"command": "mvn -q test"}}] if waste else []})
    path.write_text("".join(compact(e) + "\n" for e in events), encoding="utf-8")


def main():
    import shutil
    for stale in (HERE / "traces", HERE / "lab5-judge"):
        shutil.rmtree(stale, ignore_errors=True)
    (HERE / "SOURCE").write_text(NOTE + "\n", encoding="utf-8")
    readme = HERE / "README.md"
    if readme.is_file() and "<!-- source -->" in readme.read_text(encoding="utf-8"):
        readme.write_text(readme.read_text(encoding="utf-8").split("<!-- source -->")[0].rstrip() + "\n",
                          encoding="utf-8")
    lines = export_lines()
    (HERE / "export.jsonl").write_text("".join(compact(l) + "\n" for l in lines), encoding="utf-8")
    traces = HERE / "traces"
    traces.mkdir(exist_ok=True)
    trace(traces / "synthetic-bloated-report-sort-accents.jsonl", "bloated", waste=True)
    trace(traces / "synthetic-lean-report-sort-accents.jsonl", "lean", waste=False)
    judge_dir = HERE / "lab5-judge" / "sonnet"
    judge_dir.mkdir(parents=True, exist_ok=True)
    first = [l for l in lines if l.get("kind") == "judge" and l["pair"] == "SYNTH-01"]
    with (HERE / "lab5-human-scores.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["sample", "accuracy", "why", "scope", "format", "overall", "source"])
        for l in first:
            h = l["human"]
            writer.writerow([l["sample"]] + [max(1, min(5, h + rng.choice((-1, 0, 0, 1)))) for _ in range(4)]
                            + [h, "SYNTHETIC"])
            j = l["judge"]
            scores = {k: max(1, min(5, j + rng.choice((-1, 0, 0, 1)))) for k in ("accuracy", "why", "scope", "format")}
            scores.update(overall=j, reason="SYNTHETIC judge score (generate_synthetic.py), not a model output.")
            meta = {"turns": 1, "cost_usd": 0.0, "duration_s": 0.0, "model": MODELS["sonnet"],
                    "input_tokens": 0, "output_tokens": 0, "cache_read_tokens": 0, "cache_write_tokens": 0}
            (judge_dir / f"{l['sample']}.json").write_text(
                json.dumps({"sample": l["sample"], "model": MODELS["sonnet"], "synthetic": True,
                            "scores": scores, "meta": meta}) + "\n", encoding="utf-8")
    print(f"wrote {len(lines)} synthetic board lines, 2 traces, 8 judge files, 1 score sheet")


if __name__ == "__main__":
    main()
